"""Measure search quality on a labeled query set and write eval/search_report.md.

    python -m eval.eval_search [--seed 7] [--invoices 60]

Each query describes a line item in different words, so it shares no word with the invoice it should
find; that is what separates search by meaning from search by spelling. Goes through the real pipeline
and the real /api/search route. Digital PDFs only, so no OCR is needed.
"""
from __future__ import annotations

import argparse
import json
import random
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from fastapi.testclient import TestClient  # noqa: E402

from app.config import Settings  # noqa: E402
from app.main import create_app  # noqa: E402
from app.search import HashingEmbedder, SentenceTransformerEmbedder  # noqa: E402
from eval import synth  # noqa: E402
from tests.conftest import upload, wait_done  # noqa: E402

# query -> the catalogue item it should find (see synth.ITEMS)
QUERIES = {
    "janitorial work": "Cleaning service",
    "office seating": "Office chairs",
    "stationery for the printer": "A4 paper (box of 5)",
    "ink for the office printer": "Printer toner cartridge",
    "parcel shipping": "Courier delivery",
    "staff education session": "Training workshop",
    "ethernet hardware": "Network switch 24-port",
    "food for an event": "Catering - lunch buffet",
    "ceiling lamp": "LED panel light",
    "disaster recovery storage": "Data backup service",
    "building a web site": "Website development",
    "flights and hotels reimbursed": "Travel expenses",
    "server rental in the cloud": "Cloud hosting - monthly",
    "penetration test": "Security audit",
    "metal fixings": "Steel brackets (pack of 50)",
    "graphic designer fees": "Design work (hours)",
}
# Nothing in the catalogue relates to these, so every result is a false positive.
OFF_TOPIC = ["veterinary surgery for a horse", "tropical fish tank", "wedding dress alterations", "piano tuning"]
TOP_K = 5


def make_files(workdir: Path, n: int, seed: int) -> tuple[list[Path], dict[str, list[str]]]:
    rng = random.Random(seed)
    paths, items = [], {}
    for i in range(n):
        spec = synth.make_spec(rng, i, template=1 + i % 3, n_items=rng.randint(1, 3), currency="GBP")
        path = workdir / f"inv_{i:03}.pdf"
        synth.render_pdf([spec], path)
        paths.append(path)
        items[spec.invoice_number] = [it.description for it in spec.items]
    return paths, items


def measure(embedder, paths: list[Path], items: dict[str, list[str]], workdir: Path) -> dict:
    settings = Settings(data_dir=workdir, job_workers=2, max_files_per_request=len(paths))
    with TestClient(create_app(settings, embedder=embedder)) as c:
        ids = [x["id"] for x in upload(c, *paths).json()["accepted"]]
        wait_done(c, ids, timeout=300)
        out = {}
        for mode in ("keyword", "semantic", "hybrid"):
            hits, rr = 0, 0.0
            for q, want in QUERIES.items():
                found = c.get("/api/search", params={"q": q, "mode": mode, "limit": TOP_K}).json()["items"]
                rank = next((n for n, h in enumerate(found, 1) if want in items.get(h["data"]["invoice_number"], [])), None)
                hits += rank is not None
                rr += 1 / rank if rank else 0.0
            noise = sum(c.get("/api/search", params={"q": q, "mode": mode, "limit": TOP_K}).json()["count"] for q in OFF_TOPIC)
            out[mode] = {"hit_at_5": round(hits / len(QUERIES), 3), "mrr": round(rr / len(QUERIES), 3),
                         "off_topic_results": round(noise / len(OFF_TOPIC), 1)}
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--invoices", type=int, default=60)
    a = ap.parse_args()
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        tmp = Path(tmp)
        src = tmp / "src"
        src.mkdir()
        paths, items = make_files(src, a.invoices, a.seed)
        results = {
            "hashing-512-v1": measure(HashingEmbedder(), paths, items, tmp / "hash"),
            "all-MiniLM-L6-v2": measure(SentenceTransformerEmbedder(Settings.embedding_model), paths, items, tmp / "st"),
        }
    rows = "\n".join(
        f"| {name} | {mode} | {r['hit_at_5'] * 100:.1f}% | {r['mrr']:.3f} | {r['off_topic_results']} |"
        for name, modes in results.items() for mode, r in modes.items())
    report = f"""# Search evaluation

_Generated by `python -m eval.eval_search --seed {a.seed} --invoices {a.invoices}`._

- **Corpus:** {a.invoices} synthetic digital PDF invoices, processed through the real pipeline.
- **Queries:** {len(QUERIES)} hand-labeled queries that describe a line item without using its words, plus {len(OFF_TOPIC)} off-topic queries.
- **Hit@{TOP_K}:** share of queries with a correct invoice in the top {TOP_K}. **MRR:** mean reciprocal rank of the first correct invoice.
- **Off-topic results:** average results returned for queries that should return nothing.

| Embedder | Mode | Hit@{TOP_K} | MRR | Off-topic results |
|---|---|---|---|---|
{rows}

The queries and catalogue are small and synthetic: this compares configurations, it does not predict accuracy on real invoices.
"""
    out = Path(__file__).parent / "search_report.md"
    out.write_text(report, encoding="utf-8")
    print(report)
    print(json.dumps(results))
    return 0


if __name__ == "__main__":
    sys.exit(main())
